-- POOPIFY: схема для первой тестовой версии.
-- ВНИМАНИЕ: это публичная шуточная лента без входа в аккаунт.
-- Любой, кто знает URL проекта, может читать записи; а код комнаты не является паролем.
-- Не храните здесь настоящие медицинские/личные сведения.
create table if not exists public.poop_entries (
  id bigint generated by default as identity primary key,
  nickname text not null check (char_length(nickname) between 1 and 32),
  stool_type text not null check (stool_type in ('type1','type2','type3','type4','type5','type6','type7')),
  volume text not null check (volume in ('XS','S','M','L','XL')),
  note text not null default '' check (char_length(note) <= 180),
  room_code text not null default 'KAKA-CLUB' check (char_length(room_code) between 1 and 32),
  created_at timestamptz not null default now()
);

alter table public.poop_entries enable row level security;

-- This starter policy makes the feed publicly readable and allows anonymous inserts.
-- Do NOT use for private rooms or sensitive data. For that, add Supabase Auth + membership-based RLS.
drop policy if exists "Public can read Poopify entries" on public.poop_entries;
create policy "Public can read Poopify entries"
on public.poop_entries for select to anon, authenticated
using (true);

drop policy if exists "Public can add Poopify entries" on public.poop_entries;
create policy "Public can add Poopify entries"
on public.poop_entries for insert to anon, authenticated
with check (
  char_length(nickname) between 1 and 32
  and char_length(note) <= 180
  and char_length(room_code) between 1 and 32
);

grant select, insert on public.poop_entries to anon, authenticated;

-- Enable Realtime for live feed updates (if this statement errors because the table
-- is already in the publication, skip it and enable it in Dashboard > Database > Publications).
do $$
begin
  alter publication supabase_realtime add table public.poop_entries;
exception when duplicate_object then null;
when undefined_object then raise notice 'Publication supabase_realtime not found; enable Realtime in the dashboard.';
end $$;
